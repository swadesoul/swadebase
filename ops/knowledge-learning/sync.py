#!/usr/bin/env python3
"""Canonical local-only SWADEBASE reference index for the existing Guardian post-hook.
Uses the current allowlist and writes a change-feed row
(sssbrain.swadebase_change_events) for every added/changed/removed doc; builds an always-on
SWADEBASE core brief (core/SWADEBASE_CORE_BRIEF.md) from Bible headers + adapters registry.
Usage: sync.py [--dry-run]. No paid calls, embeddings or model training."""
from pathlib import Path
import hashlib,json,subprocess,datetime,re,sys,fnmatch,os,tempfile
ROOT=Path('/opt/swadebase/docs')
ALLOW=Path(__file__).resolve().parent/"ALLOWLIST.txt"
STATE=Path('/opt/sssbrain-ops/incident-guardian/knowledge-sync.json')
CORE='core/SWADEBASE_CORE_BRIEF.md'
SECRET=re.compile(r'\b(?:sk-[A-Za-z0-9_-]{16,}|sk_live_[A-Za-z0-9]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+)|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----')
DRY='--dry-run' in sys.argv
def write_state(report):
 # Entry checks read this concurrently. Replace one complete readable receipt.
 temporary=None
 try:
  with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',dir=STATE.parent,prefix='.knowledge-sync-',delete=False) as stream:
   temporary=Path(stream.name);json.dump(report,stream,indent=2);stream.flush();os.fsync(stream.fileno())
  temporary.chmod(0o644);os.replace(temporary,STATE);temporary=None
 finally:
  if temporary is not None:temporary.unlink(missing_ok=True)
def sql(q):
 r=subprocess.run(['docker','exec','-i','supabase-db','psql','-U','postgres','-X','-At','-v','ON_ERROR_STOP=1'],input=q,capture_output=True,text=True,timeout=60)
 if r.returncode:raise RuntimeError('knowledge_index_database_error')
 return r.stdout
def lit(s):return "'"+str(s).replace("'","''")+"'"
def chunks(text,maximum=2800):
 result=[];current=''
 for paragraph in text.split('\n\n'):
  for i in range(0,max(1,len(paragraph)),maximum):
   part=paragraph[i:i+maximum]
   if len(current)+len(part)+2>maximum and current:result.append(current);current=''
   current+=(('\n\n' if current else '')+part)
 if current:result.append(current)
 return result
def patterns():
 return [l.strip() for l in ALLOW.read_text().splitlines() if l.strip() and not l.lstrip().startswith('#')]
def allowed(rel,pats):
 if '/archive/' in '/'+rel or rel.endswith('.bak'):return False
 return any(fnmatch.fnmatch(rel,p) or (p.endswith('/**/*.md') and rel.startswith(p[:-7]) and rel.endswith('.md')) for p in pats)
def collect():
 pats=patterns();out=[]
 for p in sorted(ROOT.rglob('*.md')):
  rel=str(p.relative_to(ROOT))
  if p.is_file() and not p.is_symlink() and p.stat().st_size<=250000 and allowed(rel,pats):out.append((rel,p.read_text(errors='replace')))
 return out
def core_brief(docs):
 lines=['# SWADEBASE core brief (auto-generated)','',
  'Always-on orientation for SSS Brain / Swarvis. Regenerated by the knowledge sync. Facts here are pointers; cite the full doc via search_knowledge before acting.','',
  '## Standing rules (short)','- SWADEBASE is the locker; not Supabase cloud. Secrets live in /opt/swade-secrets and are never printed.',
  '- Merge and deploy only approved work; never break live sites. Money sites: abagale.live first, then videosaywhat, teachvirt, resinglab, tokencsi, makemycoin. Maestro Radio is not a money site.','',
  '## Indexed knowledge map']
 groups={}
 for rel,text in docs:groups.setdefault(rel.split('/')[0] if '/' in rel else 'top-level',[]).append((rel,text))
 for g,items in sorted(groups.items()):
  lines.append(f'### {g} ({len(items)} docs)')
  for rel,text in items[:60]:
   title=next((l.lstrip('# ').strip() for l in text.splitlines() if l.startswith('# ')),Path(rel).stem)
   first=next((l.strip() for l in text.splitlines() if l.strip() and not l.startswith('#')),'')[:180]
   lines.append(f'- {rel}: {title}. {first}')
 try:
  rows=json.loads(sql("SELECT coalesce(json_agg(row_to_json(a)),'[]') FROM (SELECT display_name,kind,owner_site,status,enabled,left(coalesce(purpose,what_it_is,''),160) AS purpose FROM swadebase_ops.adapters_registry ORDER BY display_name)a;").strip())
  lines+=['','## Adapters registry ('+str(len(rows))+')']+[f"- {r['display_name']} [{r['kind']}, {r['status']}, {'on' if r['enabled'] else 'off'}] site={r['owner_site'] or '-'}: {r['purpose']}" for r in rows]
 except Exception:lines+=['','## Adapters registry: unavailable at last sync']
 return '\n'.join(lines)[:24000]
def run():
 docs=collect()
 brief=core_brief(docs);docs.append((CORE,brief))
 if not DRY:
  Path(ROOT/'core').mkdir(exist_ok=True);(ROOT/CORE).write_text(brief)
 paths={rel for rel,_ in docs}
 previous=json.loads(sql("SELECT coalesce(json_agg(row_to_json(d)),'[]') FROM (SELECT doc_path,doc_sha,source FROM sssbrain.swadebase_docs)d;").strip())
 old={x['doc_path']:x for x in previous};added=[];changed=[];removed=[];skipped=[]
 st=['BEGIN;',"SET LOCAL lock_timeout='5s';","SET LOCAL statement_timeout='45s';","SELECT pg_advisory_xact_lock(hashtext('knowledge-reference-sync-v1'));"]
 def event(kind,path,digest,title):
  st.append('INSERT INTO sssbrain.swadebase_change_events(event_key,kind,title,summary,location,link,source,tags) VALUES('+','.join([lit(f'doc:{path}:{digest[:16]}'),lit(kind),lit(title[:200]),lit(f'{kind.replace("_"," ")}: {path}'),lit(path),lit('swadebase://knowledge/'+path),lit('swadebase_docs'),"ARRAY["+lit(path.split('/')[0])+"]"])+') ON CONFLICT(event_key) DO NOTHING;')
 for path,text in docs:
  digest=hashlib.sha256(text.encode()).hexdigest()
  if old.get(path,{}).get('doc_sha')==digest:continue
  if SECRET.search(text):skipped.append(path);st.append('DELETE FROM sssbrain.swadebase_docs WHERE doc_path='+lit(path)+';');continue
  title=next((l.lstrip('# ').strip() for l in text.splitlines() if l.startswith('# ')),Path(path).stem)
  parts=chunks(text);link='swadebase://knowledge/'+path
  (changed if path in old else added).append(path)
  st.append('INSERT INTO sssbrain.swadebase_docs(doc_path,source,title,link,doc_sha,byte_size,chunk_count,embedded_chunks) VALUES('+','.join([lit(path),lit('swadebase_docs'),lit(title),lit(link),lit(digest),str(len(text.encode())),str(len(parts)),'0'])+") ON CONFLICT(doc_path) DO UPDATE SET source=excluded.source,title=excluded.title,link=excluded.link,doc_sha=excluded.doc_sha,byte_size=excluded.byte_size,chunk_count=excluded.chunk_count,embedded_chunks=0,updated_at=now();")
  st.append('DELETE FROM sssbrain.swadebase_knowledge_chunks WHERE doc_path='+lit(path)+';')
  for n,part in enumerate(parts):
   heading=next((l.lstrip('# ').strip() for l in part.splitlines() if l.startswith('#')),title)
   st.append('INSERT INTO sssbrain.swadebase_knowledge_chunks(doc_path,chunk_index,source,doc_title,heading,content,link,doc_sha) VALUES('+','.join([lit(path),str(n),lit('swadebase_docs'),lit(title),lit(heading),lit(part),lit(link),lit(digest)])+');')
  if path!=CORE:event('doc_added' if path not in old else 'doc_changed',path,digest,title)
 for path,v in old.items():
  if v['source']=='swadebase_docs' and not path.startswith('/') and path not in paths:
   removed.append(path);st.append('DELETE FROM sssbrain.swadebase_docs WHERE doc_path='+lit(path)+';');event('doc_removed',path,v['doc_sha'] or 'x',path)
 st.append('COMMIT;')
 if not DRY:sql('\n'.join(st))
 report={'time_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'status':'dry_run' if DRY else 'ok','sources_considered':len(paths),'added':len(added),'changed':len(changed),'removed':len(removed),'quarantined_paths':skipped,'change_events':len(added)+len(changed)+len(removed),'core_brief_bytes':len(brief.encode()),'paid_calls':0,'embeddings_generated':0,'model_training':False}
 if DRY:report['added_paths']=added;report['changed_paths']=changed;report['removed_paths']=removed
 else:write_state(report)
 print(json.dumps(report,indent=1));return report
def main():
 try:run();return 0
 except Exception as e:
  report={'time_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'status':'failed','reason':type(e).__name__,'paid_calls':0,'embeddings_generated':0,'model_training':False}
  if not DRY:
   try:write_state(report)
   except Exception:pass
  print(json.dumps(report));return 0 if not DRY else 1
if __name__=='__main__':sys.exit(main())

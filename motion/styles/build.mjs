// Regenerates every derived copy of the motion library from styles.src.mjs:
//   motion/styles/library.json                                  (canonical JSON)
//   supabase/migrations/20261026220100_motion_styles_seed.sql   (SWADEBASE seed)
//   docker/volumes/functions/motion-studio/_shared/*            (edge-function copies)
// Usage: node motion/styles/build.mjs
import { writeFileSync, mkdirSync, copyFileSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { STYLES, CATEGORIES } from './styles.src.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../..')
const errors = []

const ids = new Set()
for (const s of STYLES) {
  if (ids.has(s.id)) errors.push(`duplicate id ${s.id}`)
  ids.add(s.id)
  for (const k of ['id', 'name', 'category', 'look', 'palette', 'type', 'motion', 'transitions', 'audio', 'bestFor', 'fit'])
    if (s[k] == null || (Array.isArray(s[k]) && !s[k].length)) errors.push(`${s.id}: missing ${k}`)
  if (!s.palette.every((c) => /^#[0-9A-F]{6}$/i.test(c))) errors.push(`${s.id}: bad palette`)
}
for (const [cat, n] of CATEGORIES) {
  const got = STYLES.filter((s) => s.category === cat).length
  if (got !== n) errors.push(`${cat}: expected ${n}, got ${got}`)
}
const known = new Set(CATEGORIES.map((c) => c[0]))
for (const s of STYLES) if (!known.has(s.category)) errors.push(`${s.id}: unknown category ${s.category}`)
if (STYLES.length !== 86) errors.push(`expected 86 styles, got ${STYLES.length}`)
if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

const library = STYLES.map((s, i) => ({ n: i + 1, ...s }))
const json = JSON.stringify({ version: 1, count: library.length, categories: CATEGORIES.map(([name, count]) => ({ name, count })), styles: library }, null, 2)
writeFileSync(resolve(here, 'library.json'), json + '\n')

const q = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`)
const rows = library.map(
  (s) =>
    `  (${q(s.id)}, ${s.n}, ${q(s.name)}, ${q(s.category)}, ${s.atlas ?? 'null'}, ${q(JSON.stringify(s))}::jsonb)`,
)
const sql = `-- GENERATED by motion/styles/build.mjs — do not hand-edit.
-- Seeds the 86-style SWADEBASE Motion Library. Re-runnable (upserts by id).
begin;
insert into public.motion_styles (id, sort_order, name, category, atlas_ref, spec)
values
${rows.join(',\n')}
on conflict (id) do update set
  sort_order = excluded.sort_order,
  name = excluded.name,
  category = excluded.category,
  atlas_ref = excluded.atlas_ref,
  spec = excluded.spec,
  updated_at = now();
commit;
`
writeFileSync(resolve(root, 'supabase/migrations/20261026220100_motion_styles_seed.sql'), sql)

const shared = resolve(root, 'docker/volumes/functions/motion-studio/_shared')
mkdirSync(shared, { recursive: true })
writeFileSync(resolve(shared, 'library.json'), json + '\n')
writeFileSync(resolve(shared, 'library.mjs'), `// GENERATED by motion/styles/build.mjs — do not hand-edit.\nexport const LIBRARY = ${json}\n`)
copyFileSync(resolve(root, 'motion/adapter/adapter.mjs'), resolve(shared, 'adapter.mjs'))
const agentSrc = readFileSync(resolve(root, 'motion/agent/motion-agent.mjs'), 'utf8').replace("from '../adapter/adapter.mjs'", "from './adapter.mjs'")
writeFileSync(resolve(shared, 'motion-agent.mjs'), agentSrc)
const appHtml = readFileSync(resolve(root, 'docker/volumes/functions/motion-studio/app.html'), 'utf8')
writeFileSync(resolve(shared, 'app-html.mjs'), `// GENERATED from ../app.html by motion/styles/build.mjs — edit app.html, then rebuild.\nexport const APP_HTML = ${JSON.stringify(appHtml)}\n`)
writeFileSync(resolve(root, 'motion/agent/agent.manifest.json'), JSON.stringify({ ...(await import('../agent/motion-agent.mjs')).AGENT_MANIFEST, tools: (await import('../agent/motion-agent.mjs')).AGENT_TOOLS }, null, 2) + '\n')
console.log(`OK: ${library.length} styles, ${CATEGORIES.length} categories, ${library.filter((s) => s.atlas).length} atlas-referenced`)

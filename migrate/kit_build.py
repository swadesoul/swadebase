#!/usr/bin/env python3
"""SWADE migration kit - build + load one app into its own SWADEBASE schema.

usage: kit_build.py <app_schema>          (source label is lovable-<app_schema>)

Reads the verified staging copy in migration_staging.inbox and:
  1. creates schema objects (types, sequences, tables, functions, primary/unique keys)
  2. brings over users that do not exist yet (matched by email; existing accounts are reused)
  3. loads every table, remapping user ids that changed
  4. adds foreign keys, indexes, row-level security, policies, triggers, grants
Nothing is dropped outside the app's own schema. Every statement's errors are logged for review.
"""
import json, re, subprocess, sys, os

APP = sys.argv[1]
SRC = f'lovable-{APP}'
WORK = f'/root/migrations/{APP}'
os.makedirs(WORK, exist_ok=True)
os.chdir(WORK)

def q(sql):
    r = subprocess.run(['docker', 'exec', 'supabase-db', 'psql', '-U', 'postgres', '-At', '-c', sql], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit('SQL failed: ' + r.stderr[:400])
    return r.stdout.strip()

def staged(kind):
    return json.loads(q(f"select coalesce(jsonb_agg(e),'[]') from migration_staging.inbox i, jsonb_array_elements(i.payload) e "
                        f"where i.source='{SRC}' and i.tbl='__ddl.{kind}'"))

def R(s):
    if s is None:
        return s
    s = re.sub(r"search_path\s+TO\s+'public'", f"search_path TO '{APP}', 'public', 'extensions'", s)
    s = re.sub(r"search_path\s+TO\s+public\b", f"search_path TO {APP}, public, extensions", s)
    s = re.sub(r"search_path\s*=\s*'?public'?", f"search_path = {APP}, public, extensions", s)
    s = re.sub(r'\bpublic\.', f'{APP}.', s)
    return s

def ident(n):
    return '"' + n.replace('"', '""') + '"'

def run(name, stmts):
    open(f'{name}.sql', 'w').write("\n".join(stmts) + "\n")
    with open(f'{name}.sql') as f, open(f'{name}.log', 'w') as lg:
        subprocess.run(['docker', 'exec', '-i', 'supabase-db', 'psql', '-U', 'postgres', '-q'], stdin=f, stdout=lg, stderr=subprocess.STDOUT)
    errs = [l for l in open(f'{name}.log') if 'ERROR' in l]
    real = [l for l in errs if 'already exists' not in l and 'multiple primary keys' not in l]
    if name == '1_schema':  # first-pass function errors are retried later in the same file
        real = [l for l in real if 'does not exist' not in l or 'relation' in l]
    print(f'{name}: {len(stmts)} statements, {len(errs)} errors, {len(real)} need review')
    for l in real[:15]:
        print('   ', re.sub(r'^psql:<stdin>:\d+: ', '', l.strip())[:230])
    return real

# ---- id map: same email already in SWADEBASE under a different id ----
pairs = q(f"select string_agg((e->>'id')||'='||u.id::text, ',') from migration_staging.inbox i, jsonb_array_elements(i.payload) e "
          f"join auth.users u on lower(u.email)=lower(e->>'email') where i.source='{SRC}' and i.tbl='auth.users' and u.id::text <> e->>'id'")
IDMAP = dict(p.split('=') for p in pairs.split(',')) if pairs else {}
json.dump(IDMAP, open('idmap.json', 'w'), indent=1)
print('id remaps:', len(IDMAP))
def remap(expr):
    for old, new in IDMAP.items():
        expr = f"replace({expr}, '{old}', '{new}')"
    return expr
P = f"({remap('i.payload::text')})::jsonb"

cols = staged('columns')
tables = {}
for c in cols:
    tables.setdefault(c['t'], []).append(c)
for cs in tables.values():
    cs.sort(key=lambda c: c['pos'])
live = set(q(f"select coalesce(string_agg(relname,chr(10)),'') from pg_class where relkind='r' and relnamespace=(select oid from pg_namespace where nspname='{APP}')").split('\n'))

# ---- 1. schema ----
S = ["set check_function_bodies = off;", f"create schema if not exists {APP};", f"set search_path = {APP}, public, extensions;"]
for e in staged('enums'):
    labels = ", ".join("'" + l.replace("'", "''") + "'" for l in e['labels'])
    S.append(f"create type {APP}.{ident(e['name'])} as enum ({labels});")
for s in staged('sequences'):
    S.append(f"create sequence if not exists {APP}.{ident(s['name'])} increment by {s.get('inc') or 1};")
    if s.get('last') is not None:
        S.append(f"select setval('{APP}.{ident(s['name'])}', {s['last']}, true);")
def coldef(c):
    d = f"{ident(c['c'])} {R(c['type'])}"
    if c.get('generated') == 's':
        return d + f" GENERATED ALWAYS AS ({R(c['default'])}) STORED"
    if c.get('identity') in ('a', 'd'):
        d += " GENERATED BY DEFAULT AS IDENTITY"
    elif c.get('default') is not None:
        d += f" DEFAULT {R(c['default'])}"
    if c['notnull']:
        d += " NOT NULL"
    return d
for f in staged('functions'):
    S.append(R(f['def']) + ";")  # first pass: column defaults may call these
for t, cs in sorted(tables.items()):
    if t not in live:
        S.append(f"create table {APP}.{ident(t)} (\n  " + ",\n  ".join(coldef(c) for c in cs) + "\n);")
for f in staged('functions'):
    S.append(R(f['def']) + ";")
cons = staged('constraints')
for k in [k for k in cons if k['type'] in ('p', 'u')]:
    S.append(f"alter table {APP}.{ident(k['t'])} add constraint {ident(k['name'])} {R(k['def'])};")
for v in staged('views'):
    S.append(f"create or replace view {APP}.{ident(v['name'])} as {R(v['def'])}")
run('1_schema', S)

# ---- 2. users + data ----
L = [f"set search_path = {APP}, public, extensions;"]
def insertable(tbl, key_tbl):
    live_cols = q(f"select string_agg(attname,',') from pg_attribute where attrelid='{tbl}'::regclass and attnum>0 and not attisdropped and attgenerated=''").split(',')
    keys = set(q(f"select coalesce(string_agg(k,','),'') from (select distinct jsonb_object_keys(e) k from migration_staging.inbox i, jsonb_array_elements(i.payload) e where i.source='{SRC}' and i.tbl='{key_tbl}') z").split(','))
    return [c for c in live_cols if c in keys]
uc = insertable('auth.users', 'auth.users')
if uc:
    L.append(f"insert into auth.users ({', '.join(ident(c) for c in uc)}) select {', '.join('r.'+ident(c) for c in uc)} from migration_staging.inbox i, "
             f"jsonb_populate_recordset(null::auth.users, i.payload) r where i.source='{SRC}' and i.tbl='auth.users' "
             f"and r.email is not null and r.email not like 'migration-%@swadesoul.com' and not exists (select 1 from auth.users u where lower(u.email)=lower(r.email)) on conflict do nothing;")
ic = insertable('auth.identities', 'auth.identities')
if ic:
    L.append(f"insert into auth.identities ({', '.join(ident(c) for c in ic)}) select {', '.join('r.'+ident(c) for c in ic)} from migration_staging.inbox i, "
             f"jsonb_populate_recordset(null::auth.identities, i.payload) r where i.source='{SRC}' and i.tbl='auth.identities' "
             f"and exists (select 1 from auth.users u where u.id=r.user_id) on conflict do nothing;")
L.append("set session_replication_role = replica;")
for t, cs in sorted(tables.items()):
    use = [c for c in cs if c.get('generated') != 's']
    cl = ", ".join(ident(c['c']) for c in use)
    rcl = ", ".join("r." + ident(c['c']) for c in use)
    L.append(f"insert into {APP}.{ident(t)} ({cl}) select {rcl} from migration_staging.inbox i, "
             f"jsonb_populate_recordset(null::{APP}.{ident(t)}, {P}) r where i.source='{SRC}' and i.tbl='public.{t}' on conflict do nothing;")
L.append("set session_replication_role = origin;")
for t, cs in sorted(tables.items()):
    for c in cs:
        if c.get('identity') in ('a', 'd'):
            L.append(f"select setval(pg_get_serial_sequence('{APP}.{ident(t)}', '{c['c']}'), coalesce((select max({ident(c['c'])}) from {APP}.{ident(t)}), 1));")
run('2_load', L)

# ---- 3. post ----
X = [f"set search_path = {APP}, public, extensions;"]
for k in [k for k in cons if k['type'] not in ('p', 'u')]:
    X.append(f"alter table {APP}.{ident(k['t'])} add constraint {ident(k['name'])} {R(k['def'])};")
for ix in staged('indexes'):
    d = R(ix['def']).replace('CREATE UNIQUE INDEX ', 'CREATE UNIQUE INDEX IF NOT EXISTS ').replace('CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS ')
    X.append(d + ";")
for r in staged('rls'):
    if r['rls']:
        X.append(f"alter table {APP}.{ident(r['t'])} enable row level security;")
X.append(f"do $$ declare p record; begin for p in select policyname, tablename from pg_policies where schemaname='{APP}' loop "
         f"execute format('drop policy %I on {APP}.%I', p.policyname, p.tablename); end loop; end $$;")
for p in staged('policies'):
    sch = APP if p['schemaname'] == 'public' else p['schemaname']
    roles = p['roles'] if isinstance(p['roles'], list) else p['roles'].strip('{}').split(',')
    s = f"create policy {ident(p['policyname'])} on {sch}.{ident(p['tablename'])} as {p['permissive']} for {p['cmd']} to {', '.join(roles)}"
    if p.get('qual'):
        s += f" using ({R(p['qual'])})"
    if p.get('with_check'):
        s += f" with check ({R(p['with_check'])})"
    X.append(s + ";")
for g in staged('triggers'):
    if g['schema'] != 'public':
        continue
    X.append(f"drop trigger if exists {ident(g['name'])} on {APP}.{ident(g['t'])};")
    X.append(R(g['def']) + ";")
X.append(f"grant usage on schema {APP} to anon, authenticated, service_role;")
X.append(f"revoke all on all tables in schema {APP} from anon, authenticated;")
gr = {}
for g in staged('grants'):
    gr.setdefault((g['t'], g['grantee']), []).append(g['priv'])
for (t, who), privs in sorted(gr.items()):
    if t in tables:
        X.append(f"grant {', '.join(sorted(set(privs)))} on {APP}.{ident(t)} to {who};")
X.append(f"grant all on all tables in schema {APP} to service_role;")
X.append(f"grant usage, select on all sequences in schema {APP} to anon, authenticated, service_role;")
X.append(f"grant execute on all functions in schema {APP} to anon, authenticated, service_role;")
X.append("notify pgrst, 'reload schema';")
run('3_post', X)
